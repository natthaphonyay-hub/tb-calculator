// สร้าง docs/ตารางตรวจมือ-การคำนวณ.md จากตัวคำนวณจริง ไว้ให้เภสัชกดเครื่องคิดเลขตาม
// ใช้: node tests/make-hand-check.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { loadEngine } from './run-engine.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const api = loadEngine();
const NAME = { H: 'H Isoniazid', R: 'R Rifampicin', Z: 'Z Pyrazinamide', E: 'E Ethambutol' };
const METHOD = { calc: 'คำนวณตามน้ำหนัก', row1: 'ตาราง 5.1 แถว 35-49.9 กก.', row2: 'ตาราง 5.1 แถว 50-69.9 กก.', row3: 'ตาราง 5.1 แถว 70 กก. ขึ้นไป' };
const FLAG = { yellow: 'เหลือง สูงกว่าช่วง', blue: 'ฟ้า ต่ำกว่าช่วง', red: 'แดง เกินขนาดสูงสุด' };
const tabsTh = (c, t) => api.tabsText(c, t, 'th');
const exact = (dose, w) => (dose / w).toFixed(3);

const L = [];
L.push('# ตารางตรวจมือ การคำนวณ TB Calculator', '',
  'สร้างจากตัวคำนวณจริงด้วย `node tests/make-hand-check.mjs` ห้ามแก้มือ ใช้กดเครื่องคิดเลขตามเพื่อตรวจ',
  'กติกาเต็มอยู่สเปก `01-สเปกกติกาคำนวณ.md` (นอก repo) ที่มา: แนวทางการควบคุมวัณโรคประเทศไทย พ.ศ. 2564 ตาราง 5.1 หน้า 60', '',
  '## 1. ช่วงที่ใช้เทียบ', '',
  '| ยา | ช่วง มก./กก./วัน | เป้าเมื่อคำนวณตามน้ำหนัก | ขนาดสูงสุด |', '|---|---|---|---|');
for (const c of api.ORDER) {
  const d = api.DRUGS[c];
  L.push(`| ${NAME[c]} | ${d.lo} ถึง ${d.hi} | ${d.target} | ${d.cap == null ? 'ไม่มีในแหล่ง' : api.num(d.cap) + ' มก.'} |`);
}
L.push('', 'มก./กก. = ขนาดยา หาร น้ำหนัก แล้วปัดครึ่งขึ้นเป็นทศนิยม 1 ตำแหน่ง ค่าที่เท่าขอบช่วงพอดีถือว่าอยู่ในช่วง', '');

L.push('## 2. น้ำหนักที่ขอบแถวและจุดเตือน', '');
const weights = ['20.0', '29.9', '30.0', '34.9', '35.0', '49.9', '50.0', '69.9', '70.0', '80.2', '80.3', '100.2', '100.3', '150.0', '200.0'];
for (const w of weights) {
  const r = api.regimen(45, w);
  L.push(`### ${w} กก. (${METHOD[r.method]})`, '', '| ยา | ขนาด | จำนวนเม็ด | กดเครื่องคิดเลข | บนจอ | ป้าย |', '|---|---|---|---|---|---|');
  for (const c of api.ORDER) {
    const x = r.drugs[c];
    let flag = x.flag ? FLAG[x.flag] : (x.atmax ? 'ขนาดสูงสุด ไม่เตือน' : 'ไม่มี');
    if (x.nowhole) flag += `, ไม่มีจำนวนเม็ดเต็มที่อยู่ในช่วง${x.alt.length ? ' อีกทาง ' + x.alt.map(api.num).join(', ') + ' มก.' : ''}`;
    if (x.suggest) flag += `, เสนอ ${api.num(x.suggest)} มก. (${tabsTh(c, api.tabsMap(c, x.suggest))}) = ${exact(x.suggest, Number(w))} ปัดเป็น ${api.fmt10(api.mgkg10(x.suggest, Math.round(Number(w) * 10)))}`;
    L.push(`| ${NAME[c]} | ${api.num(x.dose)} มก. | ${tabsTh(c, x.tabs)} | ${api.num(x.dose)} หาร ${w} = ${exact(x.dose, Number(w))} | ${x.mgkg} | ${flag} |`);
  }
  L.push('');
}

L.push('## 3. คิดทีละขั้น 3 ตัวอย่าง', '');
{
  const w = 30, d = api.DRUGS.H;
  L.push('**ก. 30.0 กก. H (คำนวณตามน้ำหนัก เพราะน้อยกว่า 35 กก.)**', '',
    `1. เป้า = ${d.target} x 30 = ${d.target * w} มก.`,
    '2. ขนาดที่จัดได้จากเม็ด 100 มก.: 100 มก. = 100 หาร 30 = 3.333 ปัด 3.3 (ต่ำกว่า 4), 200 มก. = 6.667 ปัด 6.7 (สูงกว่า 6) ไม่มีขนาดไหนอยู่ในช่วง 4 ถึง 6',
    '3. ห่างจากเป้าเท่ากัน (50 มก. ทั้งคู่) จึงเลือกขนาดสูงกว่า = 200 มก. แล้วขึ้นป้ายเหลือง บอกอีกทาง 100 มก.',
    `4. ตัวคำนวณได้ ${api.num(api.regimen(45, '30.0').drugs.H.dose)} มก. ตรงกับที่คิด`, '');
}
{
  const r = api.regimen(45, '80.5');
  L.push('**ข. 80.5 กก. E (แถว 70 กก. ขึ้นไป)**', '',
    '1. ขนาดตามตาราง E 1,200 มก. หาร 80.5 = 14.907 ปัด 14.9 ต่ำกว่า 15 จึงขึ้นป้ายฟ้า',
    '2. ขนาดที่เสนอ: เป้า 15 x 80.5 = 1,207.5 มก.',
    '3. ขนาดที่อยู่ในช่วง 15 ถึง 20 (1,207.5 ถึง 1,610 มก.) จากเม็ด 400 กับ 500: 1,300 (16.1), 1,400 (17.4), 1,500 (18.6), 1,600 (19.9)',
    '4. ใกล้ 1,207.5 ที่สุดคือ 1,300 มก. = 400 มก. 2 เม็ด + 500 มก. 1 เม็ด',
    `5. ตัวคำนวณเสนอ ${api.num(r.drugs.E.suggest)} มก. ตรงกับที่คิด`, '');
}
{
  const d = api.dates('2026-11-08');
  L.push('**ค. วันที่ เริ่มยา 8 พ.ย. 2569**', '',
    '1. บวก 2 เดือน = 8 ม.ค. 2570 ลบ 1 วัน = จบระยะเข้มข้น 7 ม.ค. 2570 (นับ 8 พ.ย. ถึง 7 ม.ค. = 23 + 31 + 7 = 61 วัน)',
    '2. เริ่มระยะต่อเนื่อง 8 ม.ค. 2570 บวกจากวันเริ่มยา 6 เดือน = 8 พ.ค. 2570 ลบ 1 วัน = ครบยา 7 พ.ค. 2570 (24 + 28 + 31 + 30 + 7 = 120 วัน)',
    `3. ตัวคำนวณได้ จบระยะเข้มข้น ${d.end_intensive} (${d.days_intensive} วัน) ครบยา ${d.end_treatment} (${d.days_continuation} วัน)`, '');
}

L.push('## 4. ปรับยาตามน้ำหนัก', '', '| น้ำหนักเดิม เป็น ใหม่ | ระยะ | ผล | ตัวที่เปลี่ยน |', '|---|---|---|---|');
for (const [a, b, ph] of [['48.0', '52.0', 'intensive'], ['49.9', '50.0', 'continuation'], ['69.0', '71.0', 'intensive'], ['69.0', '71.0', 'continuation'], ['52.0', '53.5', 'intensive'], ['34.0', '36.0', 'intensive'], ['80.2', '80.3', 'intensive']]) {
  const r = api.adjust(45, a, b, ph, null);
  const det = r.changed.map(c => `${c} ${api.num(r.old[c])} เป็น ${api.num(r.new[c])}`).join(', ') || 'ไม่มี';
  L.push(`| ${a} เป็น ${b} | ${ph === 'intensive' ? 'เข้มข้น' : 'ต่อเนื่อง'} | ${r.result === 'adjust' ? 'ปรับยา' : 'ไม่ต้องปรับยา'} | ${det} |`);
}
L.push('', '80.2 เป็น 80.3 กก. ไม่ต้องปรับยา แม้ E จะขึ้นป้ายฟ้าที่ 80.3 เพราะขนาดตามตารางเท่าเดิม ป้ายฟ้าเสนอขนาดใหม่ให้เภสัชเลือกเอง', '');

writeFileSync(join(here, '..', 'docs', 'ตารางตรวจมือ-การคำนวณ.md'), L.join('\n'));
console.log('เขียน docs/ตารางตรวจมือ-การคำนวณ.md แล้ว', L.length, 'บรรทัด');
